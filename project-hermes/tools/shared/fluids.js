const NAMES = { water: "Water", eg: "Ethylene glycol", pg: "Propylene glycol" };
const SOURCES = {
  water: "Dow DOWTHERM SR-1 guide, 0 % column",
  eg: "Dow DOWTHERM SR-1 guide, Tables 10/14/22",
  pg: "Melinder (2010) via CoolProp, checked against Dow DOWFROST data"
};

function bracket(arr, x) {
  if (x < arr[0] || x > arr[arr.length - 1]) return null;
  for (let i = 0; i < arr.length - 1; i++) if (x <= arr[i + 1]) return [i, i + 1, arr[i + 1] === arr[i] ? 0 : (x - arr[i]) / (arr[i + 1] - arr[i])];
  return [arr.length - 1, arr.length - 1, 0];
}

/**
 * props(fluid, volPct, tempF) → { ok, rho, cp, mu, sg, source } or { ok:false, reason }.
 * fluid: "water" | "eg" | "pg". Water ignores volPct.
 */
function props(fluid, volPct, tempF) {
  const key = fluid === "water" ? "eg" : fluid;
  const T = TABLES[key];
  if (!T) return { ok: false, reason: "unknown fluid" };
  const c = fluid === "water" ? 0 : volPct;
  if (typeof tempF !== "number" || !Number.isFinite(tempF)) return { ok: false, reason: "enter fluid temperature" };
  if (typeof c !== "number" || !Number.isFinite(c)) return { ok: false, reason: "enter glycol concentration" };
  if (fluid !== "water" && c < T.conc[0]) return { ok: false, reason: `concentration below ${T.conc[0]}% is outside the data; use water or ${T.conc[0]}%+` };
  const bt = bracket(T.temps, tempF), bc = bracket(T.conc, c);
  if (!bt) return { ok: false, reason: `temperature outside ${T.temps[0]}–${T.temps[T.temps.length - 1]} °F data` };
  if (!bc) return { ok: false, reason: `concentration outside ${T.conc[0]}–${T.conc[T.conc.length - 1]}% by volume data` };
  const [t0, t1, ft] = bt, [c0, c1, fc] = bc;
  function interp(m, log) {
    const q = [m[t0][c0], m[t0][c1], m[t1][c0], m[t1][c1]];
    if (q.some((v) => v === null)) return null;
    const g = log ? q.map(Math.log) : q;
    const a = g[0] + (g[1] - g[0]) * fc, b = g[2] + (g[3] - g[2]) * fc, v = a + (b - a) * ft;
    return log ? Math.exp(v) : v;
  }
  const rho = interp(T.rho), cp = interp(T.cp), mu = interp(T.mu, true);
  if (rho === null || cp === null || mu === null) {
    return { ok: false, reason: fluid === "water" ? "water data starts at 40 °F" : "below the freezing point of this mix" };
  }
  return { ok: true, rho, cp, mu, sg: rho / 62.32, source: SOURCES[fluid], name: NAMES[fluid] };
}

export { props, NAMES, SOURCES };
